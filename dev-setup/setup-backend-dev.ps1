# 根据 defaults.env 写出本机 .env 与 application-local.yaml。
# 在 backend 根目录（monorepo 的 backend/ 或独立仓 GlucoPilot-backend）执行：
#   powershell -ExecutionPolicy Bypass -File .\dev-setup\setup-backend-dev.ps1 -Force
#   powershell -ExecutionPolicy Bypass -File .\dev-setup\setup-backend-dev.ps1 -WithMinio -Force
# -Force：覆盖已有生成文件；-WithMinio：切到 minio 并 docker compose 起 MinIO、建桶。

param(
    [switch]$Force,
    [switch]$WithMinio
)

$ErrorActionPreference = 'Stop'

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$backendRoot = Split-Path -Parent $scriptDir
$defaultsPath = Join-Path $scriptDir 'defaults.env'
$envOut = Join-Path $backendRoot '.env'
$localYamlOut = Join-Path $backendRoot 'glucopilot-business\src\main\resources\application-local.yaml'
$composeMinio = Join-Path $backendRoot 'compose.minio.yaml'

if (-not (Test-Path -LiteralPath $defaultsPath)) {
    throw "defaults.env not found: $defaultsPath"
}

function Read-Defaults([string]$path) {
    $map = @{}
    Get-Content -LiteralPath $path -Encoding UTF8 | ForEach-Object {
        $line = $_.Trim()
        if (-not $line -or $line.StartsWith('#')) { return }
        $eq = $line.IndexOf('=')
        if ($eq -lt 1) { return }
        $key = $line.Substring(0, $eq).Trim()
        $val = $line.Substring($eq + 1)
        $map[$key] = $val
    }
    return $map
}

function Write-IfAllowed([string]$path, [string]$content, [switch]$force) {
    if ((Test-Path -LiteralPath $path) -and -not $force) {
        Write-Host "Skip existing: $path (add -Force to overwrite)"
        return $false
    }
    $dir = Split-Path -Parent $path
    if (-not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    [System.IO.File]::WriteAllText($path, $content, [System.Text.UTF8Encoding]::new($false))
    Write-Host "Wrote: $path"
    return $true
}

function Set-EnvKey([string]$envText, [string]$key, [string]$value) {
    $pattern = "(?m)^" + [regex]::Escape($key) + "=.*$"
    $replacement = "$key=$value"
    if ($envText -match $pattern) {
        return [regex]::Replace($envText, $pattern, $replacement)
    }
    return $envText.TrimEnd() + "`n$key=$value`n"
}

$defaults = Read-Defaults $defaultsPath
$opsSecret = $defaults['OPS_TOKEN_SECRET']
if ([string]::IsNullOrWhiteSpace($opsSecret) -or $opsSecret.Length -lt 64) {
    throw 'OPS_TOKEN_SECRET in defaults.env must be at least 64 characters'
}

$fixedOpenid = ''
if ($defaults.ContainsKey('WECHAT_MOCK_FIXED_OPENID')) {
    $fixedOpenid = [string]$defaults['WECHAT_MOCK_FIXED_OPENID']
}

$accessKey = if ($defaults['MINIO_ACCESS_KEY']) { $defaults['MINIO_ACCESS_KEY'] } else { 'minioadmin' }
$secretKey = if ($defaults['MINIO_SECRET_KEY']) { $defaults['MINIO_SECRET_KEY'] } else { 'minioadmin' }
$bucket = if ($defaults['MINIO_BUCKET']) { $defaults['MINIO_BUCKET'] } else { 'glucopilot' }

$envHeader = @"
# Generated by backend/dev-setup/setup-backend-dev.ps1 - do not commit.
# Edit backend/dev-setup/defaults.env then re-run (add -Force to overwrite).

"@
$defaultsRaw = [System.IO.File]::ReadAllText($defaultsPath, [System.Text.UTF8Encoding]::new($false))
$envContent = $envHeader + $defaultsRaw.TrimEnd() + "`n"

if ($WithMinio) {
    $envContent = Set-EnvKey $envContent 'STORAGE_PROVIDER' 'minio'
}

$wroteEnv = Write-IfAllowed -path $envOut -content $envContent -force:$Force
if (-not $wroteEnv -and $WithMinio -and (Test-Path -LiteralPath $envOut)) {
    # Ensure STORAGE_PROVIDER=minio even when .env was skipped without -Force
    $existing = [System.IO.File]::ReadAllText($envOut, [System.Text.UTF8Encoding]::new($false))
    $updated = Set-EnvKey $existing 'STORAGE_PROVIDER' 'minio'
    if ($updated -ne $existing) {
        [System.IO.File]::WriteAllText($envOut, $updated, [System.Text.UTF8Encoding]::new($false))
        Write-Host "Updated STORAGE_PROVIDER=minio in: $envOut"
    }
}

$openidYaml = if ([string]::IsNullOrWhiteSpace($fixedOpenid)) {
    '    fixed-openid: ""'
} else {
    "    fixed-openid: `"$($fixedOpenid.Replace('\','\\').Replace('"','\"'))`""
}

$yamlContent = @"
# Generated by backend/dev-setup/setup-backend-dev.ps1 - do not commit.
# Start with Spring profiles: dev,local
# Edit backend/dev-setup/defaults.env then re-run with -Force.

token:
  secret: `"$opsSecret`"

wechat:
  mock:
$openidYaml
"@

Write-IfAllowed -path $localYamlOut -content $yamlContent -force:$Force | Out-Null

if ($WithMinio) {
    if (-not (Test-Path -LiteralPath $composeMinio)) {
        throw "compose.minio.yaml not found: $composeMinio"
    }
    $docker = Get-Command docker -ErrorAction SilentlyContinue
    if (-not $docker) {
        throw 'docker not found. Install Docker Desktop or run without -WithMinio (STORAGE_PROVIDER=local).'
    }
    # Must match image tags in compose.minio.yaml（第三方镜像，避开官方 Hub 经加速器 403）
    $minioImages = @(
        'netvark/minio:latest',
        'netvark/mc:latest'
    )
    Write-Host 'Checking Docker engine...'
    # NativeCommandError must not abort under $ErrorActionPreference=Stop
    $prevEap = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    & docker info 1>$null 2>$null
    if ($LASTEXITCODE -ne 0) {
        $ErrorActionPreference = $prevEap
        throw 'Docker engine not running. Start Docker Desktop, then re-run. Config files were already written.'
    }
    Write-Host 'Checking MinIO images (skip pull if already local)...'
    foreach ($img in $minioImages) {
        & docker image inspect $img 1>$null 2>$null
        $haveImage = ($LASTEXITCODE -eq 0)
        if ($haveImage) {
            Write-Host "  already present, skip pull: $img"
        } else {
            Write-Host "  not found, pulling: $img"
            & docker pull $img
            if ($LASTEXITCODE -ne 0) {
                $ErrorActionPreference = $prevEap
                # ASCII only: console code page may garble Chinese in throw
                throw "docker pull failed: $img (exit $LASTEXITCODE). Config already written. Your Docker registry-mirrors (e.g. daocloud) returned 403/502 — fix mirrors in Docker Desktop, or use 一键配置.cmd for local storage (no MinIO)."
            }
        }
    }
    $ErrorActionPreference = $prevEap
    Write-Host "Starting MinIO and creating bucket '$bucket'..."
    Push-Location $backendRoot
    try {
        $env:MINIO_ACCESS_KEY = $accessKey
        $env:MINIO_SECRET_KEY = $secretKey
        $env:MINIO_BUCKET = $bucket
        & docker compose -f compose.minio.yaml up -d
        if ($LASTEXITCODE -ne 0) {
            throw "docker compose failed (exit $LASTEXITCODE). Start Docker Desktop, then re-run with -WithMinio. Config files were already written."
        }
        # Wait for init container to finish (create-or-skip bucket)
        $deadline = (Get-Date).AddMinutes(2)
        do {
            $ps = & docker compose -f compose.minio.yaml ps -a --format json 2>$null
            Start-Sleep -Seconds 2
            $initDone = $false
            try {
                $rows = $ps | ConvertFrom-Json
                if ($rows -isnot [System.Array]) { $rows = @($rows) }
                $init = $rows | Where-Object { $_.Service -eq 'minio-init' -or $_.Name -like '*minio-init*' }
                if ($init) {
                    $st = [string]$init.State
                    if ($st -match 'exited|dead') { $initDone = $true }
                }
            } catch {
                # older compose: fall through to network probe
            }
            try {
                $tcp = Test-NetConnection -ComputerName 127.0.0.1 -Port 9000 -WarningAction SilentlyContinue
                if ($tcp.TcpTestSucceeded -and ((Get-Date) -gt $deadline.AddSeconds(-90))) {
                    # MinIO up long enough; treat as ok even if ps parse failed
                    $initDone = $true
                }
            } catch { }
        } while (-not $initDone -and (Get-Date) -lt $deadline)

        # Fallback: ensure bucket via one-shot mc on the compose network
        $netName = 'glucopilot-minio_default'
        $networks = & docker network ls --format '{{.Name}}' 2>$null
        if ($networks -match 'glucopilot-minio') {
            $netName = ($networks | Where-Object { $_ -like '*glucopilot-minio*' } | Select-Object -First 1)
        }
        # Fallback: mb + CORS（netvark/mc ENTRYPOINT=mc，须 --entrypoint /bin/sh）
        $mcCmd = @'
mc alias set local http://minio:9000 "$MINIO_ACCESS_KEY" "$MINIO_SECRET_KEY"
mc mb -p "local/$MINIO_BUCKET" || true
cat > /tmp/cors.xml <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<CORSConfiguration xmlns="http://s3.amazonaws.com/doc/2006-03-01/">
  <CORSRule>
    <AllowedOrigin>*</AllowedOrigin>
    <AllowedMethod>GET</AllowedMethod>
    <AllowedMethod>PUT</AllowedMethod>
    <AllowedMethod>POST</AllowedMethod>
    <AllowedMethod>HEAD</AllowedMethod>
    <AllowedHeader>*</AllowedHeader>
    <ExposeHeader>ETag</ExposeHeader>
    <ExposeHeader>Content-Length</ExposeHeader>
    <ExposeHeader>Content-Type</ExposeHeader>
    <MaxAgeSeconds>3600</MaxAgeSeconds>
  </CORSRule>
</CORSConfiguration>
EOF
mc cors set "local/$MINIO_BUCKET" /tmp/cors.xml || true
'@
        & docker run --rm --network $netName `
            --entrypoint /bin/sh `
            -e "MINIO_ACCESS_KEY=$accessKey" `
            -e "MINIO_SECRET_KEY=$secretKey" `
            -e "MINIO_BUCKET=$bucket" `
            netvark/mc:latest `
            -c $mcCmd | Out-Host
        Write-Host "MinIO ready. Bucket: $bucket (CORS for browser PUT). Console: http://127.0.0.1:9001"
    } finally {
        Pop-Location
        Remove-Item Env:MINIO_ACCESS_KEY -ErrorAction SilentlyContinue
        Remove-Item Env:MINIO_SECRET_KEY -ErrorAction SilentlyContinue
        Remove-Item Env:MINIO_BUCKET -ErrorAction SilentlyContinue
    }
}

Write-Host ''
Write-Host 'Done. Start backend with profiles: dev,local'
Write-Host 'Edit defaults: backend/dev-setup/defaults.env (or ./dev-setup/defaults.env in this repo)'
if ($WithMinio) {
    Write-Host 'STORAGE_PROVIDER=minio; bucket auto-created via compose.minio.yaml'
} else {
    Write-Host 'Default STORAGE_PROVIDER=local. Add -WithMinio to start MinIO and create the bucket.'
}
