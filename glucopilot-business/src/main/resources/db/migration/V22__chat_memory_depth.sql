-- ② 期：记忆深度（token 预算窗口 + 滚动摘要 + 工具结果回放）里的两处结构变更。
--
-- 1) 新场景 SUMMARY 的提示词进库（与其它场景同一条路：库表优先、classpath 兜底、后台可改可回滚）。
--    它不面向用户，产物是内部上下文；单独成场景是为了可以挑更便宜的模型、用自己的温度与提示词。
--
-- 2) chat_tool_call.result_digest：工具结果的**关键字段摘要**（≤512 字）。
--    ① 期只落了元数据（谁被调了/成没成/多久），于是模型回放时看不到"上一轮查到的数据"，
--    追问只能重新调工具（重复计费，还可能给出不同结果）。这里补上摘要列，让历史里能带上数据；
--    **仍然不存完整 JSON**：那是用户血糖、饮食的原始数据，多存一份就多一份隐私与脱敏责任。
--
-- 说明：摘要正文（chat_session.context_summary / summary_upto_msg_id）**不需要新列**——
-- 这两列从 V1 就存在且一直没人用，本轮正式启用。

-- ---------------------------------------------------------------------------
-- 1) 工具结果摘要列
-- ---------------------------------------------------------------------------
SET @gp_add_digest := (
    SELECT IF(COUNT(*) = 0,
        'ALTER TABLE chat_tool_call ADD COLUMN result_digest VARCHAR(512) NULL COMMENT ''工具结果的关键字段摘要（≤512字，供会话记忆回放；刻意不存完整返回）''',
        'DO 0')
      FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'chat_tool_call' AND COLUMN_NAME = 'result_digest');
PREPARE gp_stmt FROM @gp_add_digest; EXECUTE gp_stmt; DEALLOCATE PREPARE gp_stmt;

