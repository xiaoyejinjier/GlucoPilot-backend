-- V51：模型配置「保存时跳过了连通性校验」的原因
--
-- 背景：后台保存模型配置时会先发一次探针请求（文本模型 ping、视觉模型发 1×1 PNG），
-- 失败直接 400 不落库——这类错误（模型名不存在 / 密钥属于别的账号 / baseUrl 少 /v1）
-- 在保存时不暴露就只能在用户提问时暴露。
--
-- 但"暂时连不通但需要先录进来"是真实需求（新厂商还没开通、本地没有外网），所以允许勾选跳过。
-- 跳过必须给原因，且原因要单独存储：写进 remark 会把运营填的业务备注冲掉，事后也分不清
-- 哪句是人写的、哪句是系统写的。
--
-- 语义：NULL = 保存时校验过（历史行同样是 NULL，早于本列引入）；
--       非 NULL = 那次保存跳过了校验，这里是当时填的理由。

ALTER TABLE ai_model_config
    ADD COLUMN verify_skipped_reason VARCHAR(255) NULL
        COMMENT '保存时跳过连通性校验的原因；NULL=校验过（或早于本列的历史行）'
        AFTER last_test_message;
