-- V61：会话「长期记忆已抽取到哪一条」
--
-- 背景：长期记忆有三个写入入口（工具当轮记、会话结束时复盘、归档补齐）。
-- 前两个各自独立；归档补齐却需要一个判断依据——「这个归档会话的记忆是不是已经抽过了」。
-- 起初的设计想用一个布尔的「抽过没有」标记，但那会误伤：用户在会话结束前刚用工具记过一条，
-- 结束时仍然应该整段复盘（工具只看了当轮一句），布尔标记却会把终局抽取直接抑制掉。
--
-- 所以记的是**位置**而不是**状态**：
--   NULL                     → 从未窗口抽取过；
--   某个消息 id              → 那一次抽取的输入窗口上界（近期窗口的最后一条消息）。
--
-- 语义边界（读这一列的人必须知道）：它是「输入窗口上界」，**不是完整性证明**。
-- 抽取只回看 ai.memory.memory-extract-window-messages × max-windows 条，
-- 早期消息可能从未进入任何窗口；因此本列只用于「归档时值不值得再抽一次」的启发式判断，
-- 不能用来回答「这个会话的记忆抽全了吗」。
--
-- 谁会写它：
--   UserChatMemoryServiceImpl.runExtract —— 窗口抽取成功结束后按上界更新（带条件，只前进）；
--   save_long_term_memory（工具路径）—— **不写**：工具抽的是当轮一句话，不代表更早的消息被覆盖。
-- 谁会读它：
--   ChatSessionServiceImpl.archiveIdleSessions —— 归档前挑一个「归档后本该抽但还没抽」的会话，
--   每次列表请求最多补抽 1 个（惰性归档是列表请求的副作用，不能因为补抽把它拖垮）。

ALTER TABLE chat_session
    ADD COLUMN memory_extracted_upto_msg_id BIGINT UNSIGNED NULL
        COMMENT '长期记忆已抽取到的消息 id（输入窗口上界，不是完整性证明）；NULL=从未窗口抽取'
        AFTER summary_upto_msg_id;
