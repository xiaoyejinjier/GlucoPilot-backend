-- 金额统一按“分”保存；本期只建订单表，不创建余额、不模拟资金到账。
CREATE TABLE wallet_recharge_order (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_no VARCHAR(64) NOT NULL COMMENT '服务端生成的充值订单号',
    user_id BIGINT UNSIGNED NOT NULL,
    amount_cents INT UNSIGNED NOT NULL COMMENT '充值金额，单位分',
    currency CHAR(3) NOT NULL DEFAULT 'CNY',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    payment_provider VARCHAR(24) NOT NULL DEFAULT 'ALIPAY_SANDBOX',
    provider_trade_no VARCHAR(96) NULL COMMENT '验签确认的渠道交易号',
    client_request_id VARCHAR(64) NOT NULL COMMENT '同用户请求幂等键',
    paid_at DATETIME(3) NULL,
    credited_at DATETIME(3) NULL COMMENT '未来钱包账本实际入账时间',
    closed_at DATETIME(3) NULL,
    refunded_cents INT UNSIGNED NOT NULL DEFAULT 0,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    gmt_create DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    gmt_modified DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_recharge_order_no (order_no),
    UNIQUE KEY uk_recharge_user_request (user_id, client_request_id),
    UNIQUE KEY uk_recharge_provider_trade (payment_provider, provider_trade_no),
    KEY idx_recharge_user_status_created (user_id, status, gmt_create, id),
    KEY idx_recharge_user_created (user_id, gmt_create, id),
    CONSTRAINT ck_recharge_amount CHECK (amount_cents BETWEEN 100 AND 100000),
    CONSTRAINT ck_recharge_currency CHECK (currency = 'CNY'),
    CONSTRAINT ck_recharge_status CHECK (status IN ('PENDING','PAID','CLOSED','REFUNDING','REFUNDED')),
    CONSTRAINT ck_recharge_refund CHECK (refunded_cents <= amount_cents)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户钱包充值订单';

CREATE TABLE consultation_order (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_no VARCHAR(64) NOT NULL COMMENT '服务端生成的问诊订单号',
    user_id BIGINT UNSIGNED NOT NULL COMMENT '问诊患者',
    consultation_id BIGINT UNSIGNED NOT NULL,
    report_id BIGINT UNSIGNED NOT NULL,
    doctor_user_id BIGINT UNSIGNED NOT NULL COMMENT '出具问诊单的医生',
    amount_cents INT UNSIGNED NOT NULL DEFAULT 100 COMMENT '查看问诊单固定1元',
    currency CHAR(3) NOT NULL DEFAULT 'CNY',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    payment_provider VARCHAR(24) NOT NULL DEFAULT 'ALIPAY_SANDBOX',
    provider_trade_no VARCHAR(96) NULL,
    client_request_id VARCHAR(64) NOT NULL,
    paid_at DATETIME(3) NULL,
    unlocked_at DATETIME(3) NULL COMMENT '服务端实际授予报告阅读权限的时间',
    closed_at DATETIME(3) NULL,
    settlement_status VARCHAR(16) NOT NULL DEFAULT 'NOT_READY' COMMENT '医生结算尚未开放',
    settled_at DATETIME(3) NULL,
    refunded_cents INT UNSIGNED NOT NULL DEFAULT 0,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    gmt_create DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    gmt_modified DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    -- 已关闭/已退款订单不占用报告名额；不允许重复创建有效订单或重复购买。
    active_report_id BIGINT UNSIGNED GENERATED ALWAYS AS (
        CASE WHEN status IN ('PENDING','PAID','REFUNDING') THEN report_id ELSE NULL END
    ) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uk_consultation_order_no (order_no),
    UNIQUE KEY uk_consultation_user_request (user_id, client_request_id),
    UNIQUE KEY uk_consultation_provider_trade (payment_provider, provider_trade_no),
    UNIQUE KEY uk_consultation_user_active_report (user_id, active_report_id),
    KEY idx_consultation_order_user_status (user_id, status, gmt_create, id),
    KEY idx_consultation_order_user_created (user_id, gmt_create, id),
    KEY idx_consultation_order_doctor (doctor_user_id, settlement_status),
    CONSTRAINT ck_consultation_order_amount CHECK (amount_cents = 100),
    CONSTRAINT ck_consultation_order_currency CHECK (currency = 'CNY'),
    CONSTRAINT ck_consultation_order_status CHECK (status IN ('PENDING','PAID','CLOSED','REFUNDING','REFUNDED')),
    CONSTRAINT ck_consultation_order_settlement CHECK (settlement_status IN ('NOT_READY','PENDING','SETTLED','CANCELLED')),
    CONSTRAINT ck_consultation_order_refund CHECK (refunded_cents <= amount_cents)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='患者支付1元查看医生问诊单的订单';
