-- 为图片消息增加「图片内容摘要」（多模态阶段 1 的产物）。
--
-- 为什么需要这一列：
--   纯图片消息（msg_type=2）的 content_text 为空，而 MyBatisChatMemoryRepository.toMessage()
--   会丢弃文本为空的行 —— 于是图片永远进不了会话记忆。用户发完图再问「那我晚饭吃多少」，
--   模型完全不知道刚才有张图。
--   但也不能把视觉模型的描述写进 content_text：那是前端气泡里显示的「用户原话」，
--   写进去用户会看到自己「说」了一段从没说过的话。
--
-- 与语音的 asr_text 形成对称（这是选「新增列」而不是复用字段的理由）：
--   asr_text      = 语音消息经 ASR 后的文本
--   media_caption = 图片消息经视觉模型识别后的文本
--   两者语义相同：原始媒体经识别后、可参与记忆回放与后续轮次的文本形式。
--
-- 写入时机：本轮流式补全结束、助手消息落库的同一个回调里一次性回填。
--   客户端取消或超时的轮次不会写入（与既有的「取消轮次不落库」一致），因此允许 NULL。
--
-- ⚠️ 这是 chat_message 上唯一的 UPDATE。该表的设计是「只追加」，
--    此处属受控例外：只把派生字段填一次，既不修改用户原话，也不修改已落库的助手回复。

ALTER TABLE chat_message
  ADD COLUMN media_caption VARCHAR(1024) NULL
  COMMENT '图片内容摘要(多模态阶段1产物，供会话记忆回放)' AFTER asr_text;
